/**
 * GATE: no-rederivation — criterion D4.  →  `NO-REDERIVATION OK — 8 of 8 interfaces`
 *
 *   > **D4.** *"None of the eight interfaces in handoff §2 is re-derived anywhere in the app — one
 *   > static check per interface, each named."*
 *
 * The handoff's own sentence for why:
 *
 *   > *"Each is a decision already made, with an authority behind it. **Re-deriving one is how two
 *   > answers to the same question start shipping.**"*
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * THE POPULATION IS NOT HAND-LISTED HERE. It is read from `tools/p2/interfaces.json`, generated by
 * `campaign-p2/bin/p2-interfaces.mjs` out of `authority/P1_TO_P2_HANDOFF.md` §2 and parity-checked
 * in the pipeline preflight. This gate therefore fails if the handoff grows a ninth interface and
 * nobody wrote a check for it — which is the only way "one static check per interface" can mean
 * anything a year from now. Every check below is bound to an interface ID, and an ID in the mirror
 * with no check bound to it is a hard failure, not a silent skip.
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * WHAT "RE-DERIVED" MEANS HERE, STATED PER INTERFACE RATHER THAN ASSUMED
 *
 * Today this app has NO ADAPTER — D1 lands in Phase 7 — and consumes no pack. So for most of the
 * eight the honest finding is *"the app does not compute this, and here is the population searched
 * to establish that"*. That is a real finding and not a vacuous one, because:
 *
 *   · the population is derived (every file under `src/**`), never a list;
 *   · every check is watched to fire by `tools/p2/rederivation-controls.mjs`, which injects a real
 *     re-derivation of each interface and requires the check to catch it;
 *   · a check whose search finds ZERO files to search is reported as a failure, not a pass.
 *
 * The checks look for the ACT of deriving — a declaration, an assignment, a computation — and not
 * for the mere mention of a name. An app that imports `intervalRankability` from the adapter and
 * renders it is doing exactly what the handoff asks. An app that computes one has re-derived it.
 */
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ok, fail } from '../lib/report.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));

export const CRITERIA = ['D4'];
export const SENTINEL = 'NO-REDERIVATION OK — 8 of 8 interfaces';

const MIRROR = join(HERE, '..', 'interfaces.json');

// ─────────────────────────────────────────────────────────────────────────────── source scanning
const walk = (dir, acc = []) => {
  if (!existsSync(dir)) return acc;
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/\.(ts|tsx|js|jsx)$/.test(e)) acc.push(p);
  }
  return acc;
};

const stripComments = (src) => src
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');

/** Every file under src/**, with comments stripped and strings intact. */
export const sources = (root) => walk(join(root, 'src')).map((abs) => ({
  file: relative(root, abs).replace(/\\/g, '/'),
  code: stripComments(readFileSync(abs, 'utf8')),
}));

const lineAt = (code, index) => code.slice(0, index).split('\n').length;

/** A file is exempt when it IS the adapter — the one place these may legitimately live. */
const isAdapter = (file) => /^src\/data\/adapter\//.test(file);

/**
 * Find every place a pattern matches in code that is not the adapter, returning named hits.
 * `why` explains, in the finding itself, what act was detected — so a violation reads as an
 * accusation somebody can check rather than as a regex id.
 */
const findAll = (files, pattern, why) => {
  const hits = [];
  for (const { file, code } of files) {
    if (isAdapter(file)) continue;
    for (const m of code.matchAll(pattern)) {
      hits.push({ file, line: lineAt(code, m.index), why, text: m[0].replace(/\s+/g, ' ').slice(0, 90) });
    }
  }
  return hits;
};

// ─────────────────────────────────────────────────────────────────────── the eight named checks
//
// Each is keyed by the interface ID the mirror assigns, so the binding between a check and the
// handoff row it discharges is explicit and machine-checked below.

const CHECKS = {
  /**
   * IF-1 — the native fact and its `quoteUnit`. Re-deriving means *"performing, in a second place
   * and with a second rounding rule, a conversion the pipeline deliberately does not perform"*.
   * The act to catch is ARITHMETIC ON A QUOTE UNIT, not the word appearing.
   */
  'IF-1': (files) => [
    ...findAll(files, /\b(quoteUnit|nativeFact|nativeValue)\b[^\n;]{0,60}[*/][^\n;=]{0,40}/g,
      'arithmetic applied to a native fact or its quote unit'),
    ...findAll(files, /\bfunction\s+(convert|normalise|normalize)(Quote|Native)[A-Za-z]*\s*\(/g,
      'a function that converts or normalises a native quote'),
    ...findAll(files, /\b(toNativeUnit|fromNativeUnit|convertQuoteUnit|rescaleNative)\s*[=(]/g,
      'a named quote-unit conversion'),
  ],

  /**
   * IF-2 — the provenance chip and the `consumability` verdict. Re-deriving means *"a second
   * grading vocabulary that disagrees with the packs' own"*. The act is DECLARING the vocabulary,
   * or deciding a verdict, in app code.
   */
  // THE ONE MODULE THAT MAY DECLARE THE VOCABULARY IS THE ONE CHECKED AGAINST THE CONTRACT.
  //
  // IF-2's danger is "a second grading vocabulary that disagrees with the packs' own". A vocabulary
  // generated from SMARTCARD_DATA_CONTRACT.md §2 and parity-checked in the pipeline preflight
  // (check 4f) cannot disagree with it — a divergence fails the preflight before any gate runs.
  //
  // Exempted by name, not by pattern: a blanket exemption for "anything with Chip in the filename"
  // would cover the next module somebody names that way.
  'IF-2': (files) => [
    ...findAll(files.filter((f) => f.file !== 'src/authority/provenanceChip.ts'),
      /\b(type|enum|const)\s+\w*(Consumability|ProvenanceGrade|ProvenanceChip)\w*\s*[=:{]/g,
      'a consumability or provenance vocabulary declared in the app'),
    ...findAll(files, /\bfunction\s+\w*(gradeProvenance|decideConsumability|classifyProvenance)\w*\s*\(/g,
      'a function deciding a provenance or consumability verdict'),
    ...findAll(files, /\bconsumability\s*[:=]\s*['"`]/g,
      'a consumability verdict assigned from a literal'),
  ],

  /**
   * IF-3 — `intervalRankability`. Re-deriving means *"classifying a conflict axis without the
   * estate, which is the evidence that decides it"*. Reading it is correct; ASSIGNING it is not.
   */
  'IF-3': (files) => [
    ...findAll(files, /\bintervalRankability\s*[:=](?!=)\s*(?!.*\b(props|adapter|result|data|row|pack)\b)[^\n;]{1,60}/g,
      'intervalRankability assigned a computed value in the app'),
    ...findAll(files, /\bfunction\s+\w*(rankInterval|computeRankability|deriveRankability)\w*\s*\(/g,
      'a function computing interval rankability'),
  ],

  /**
   * IF-4 — `conflictRenderPlan`. Re-deriving means *"inventing a winner where the pipeline refused
   * to name one"*. This is also a HARD PROHIBITION of the campaign (OB-6): no conflict-axis
   * classifier may be implemented in P2 at all.
   */
  'IF-4': (files) => [
    ...findAll(files, /\bconflictRenderPlan\s*[:=](?!=)/g,
      'a conflictRenderPlan constructed in the app'),
    ...findAll(files, /\bfunction\s+\w*(classifyConflict|resolveConflict|pickConflictWinner|conflictAxis)\w*\s*\(/g,
      'a conflict classifier — also forbidden outright by OB-6'),
  ],

  /**
   * IF-5 — the canonical shipping resolver, one per pack set. Re-deriving means *"an object
   * computing its own shipping predicate — the exact defect S15 closed for `stacking`"*.
   */
  'IF-5': (files) => [
    ...findAll(files, /\bfunction\s+\w*(isShipped|shipsWith|resolveShipping|shippingPredicate)\w*\s*\(/g,
      'a shipping predicate computed in the app'),
    ...findAll(files, /\b(get|compute|derive)Shipping[A-Za-z]*\s*[=(]/g,
      'a shipping resolver defined in the app'),
  ],

  /**
   * IF-6 — the composition map. Re-deriving means *"a reference the build does not check, found
   * later by a harness instead of by the build that created it"*.
   */
  'IF-6': (files) => [
    ...findAll(files, /\b(const|let|type)\s+\w*[Cc]ompositionMap\w*\s*[=:]/g,
      'a composition map declared in the app'),
    ...findAll(files, /\bfunction\s+\w*(buildComposition|composePackSet|deriveComposition)\w*\s*\(/g,
      'a composition map computed in the app'),
  ],

  /**
   * IF-7 — the compatibility matrices. Re-deriving means *"a load-time check replaced by prose
   * nobody enforces"*.
   */
  'IF-7': (files) => [
    ...findAll(files, /\b(const|let|type)\s+\w*(CompatibilityMatrix|COMPATIBILITY_MATRIX)\w*\s*[=:]/g,
      'a compatibility matrix declared in the app'),
    ...findAll(files, /\bfunction\s+\w*(checkCompatibility|isCompatibleWith|deriveCompatibility)\w*\s*\(/g,
      'a compatibility check implemented in the app'),
  ],

  /**
   * IF-8 — `EXPECTED_DATASET_ID` and the trust store. The handoff says these are COMPILED IN. Re-
   * deriving means *"a check a pack can influence, which is not a check"* — so the failure to catch
   * is the value arriving from data rather than from source.
   */
  'IF-8': (files) => [
    ...findAll(files, /\bEXPECTED_DATASET_ID\s*[:=]\s*(?!['"`])[A-Za-z_$][\w$]*[.[]/g,
      'EXPECTED_DATASET_ID taken from a value rather than compiled in — a pack could influence it'),
    ...findAll(files, /\b(trustStore|TRUST_STORE|trustedKeys)\s*[:=]\s*(JSON\.parse|require|await\s+import)/g,
      'the trust store loaded from data rather than compiled in'),
  ],
};

// ────────────────────────────────────────────────────────────────────────────────────── the gate
export const run = async ({ root }) => {
  const problems = [];
  const lines = [];

  if (!existsSync(MIRROR)) {
    return fail('tools/p2/interfaces.json is missing — the population for D4 comes from handoff §2 via '
      + 'campaign-p2/bin/p2-interfaces.mjs, and this gate will not hand-list the eight itself');
  }
  const mirror = JSON.parse(readFileSync(MIRROR, 'utf8'));
  const interfaces = mirror.interfaces ?? [];

  if (interfaces.length === 0) {
    return fail('the interface mirror is empty — "0 of 0" is not a pass');
  }
  if (mirror.contractRequires !== interfaces.length) {
    problems.push('the mirror carries ' + interfaces.length + ' interfaces and says the contract requires '
      + mirror.contractRequires + ' — regenerate it; the two documents disagree');
  }

  // BINDING: every interface must have a check, and every check must have an interface.
  const unchecked = interfaces.filter((i) => !CHECKS[i.id]);
  const orphanChecks = Object.keys(CHECKS).filter((id) => !interfaces.some((i) => i.id === id));
  for (const i of unchecked) {
    problems.push(i.id + ' (' + i.name + ') has NO CHECK in this gate — D4 requires one static check per interface');
  }
  for (const id of orphanChecks) {
    problems.push('this gate has a check for ' + id + ', which the handoff no longer lists — a check for '
      + 'nothing reads as coverage and is not');
  }

  const files = sources(root);
  if (files.length === 0) {
    return fail('scanned 0 files under src/ — an empty population cannot clear eight interfaces');
  }
  lines.push('population      ' + files.length + ' files under src/** · adapter exempt: '
    + (existsSync(join(root, 'src', 'data', 'adapter')) ? 'src/data/adapter/** exists' : 'src/data/adapter/** does not exist yet (D1, Phase 7), so NOTHING is exempt'));
  lines.push('mirror          ' + mirror.source + ' · ' + interfaces.length + ' interfaces');
  lines.push('');

  let cleared = 0;
  for (const iface of interfaces) {
    const check = CHECKS[iface.id];
    if (!check) continue;
    const hits = check(files);
    if (hits.length === 0) cleared += 1;
    lines.push('  ' + iface.id + '  ' + (hits.length === 0 ? 'not re-derived' : String(hits.length) + ' HIT(S)      ')
      + '  ' + iface.name);
    lines.push('        lives in: ' + iface.livesIn);
    for (const h of hits.slice(0, 4)) {
      lines.push('        RE-DERIVED  ' + h.file + ':' + h.line + '  ' + h.why);
      lines.push('                    ' + h.text);
      problems.push(iface.id + ' re-derived at ' + h.file + ':' + h.line + ' — ' + h.why);
    }
    if (hits.length > 4) lines.push('        … and ' + (hits.length - 4) + ' more');
  }

  // --- every check must have been watched to fire ------------------------------------
  const CONTROL = join(HERE, '..', 'rederivation-controls.json');
  if (!existsSync(CONTROL)) {
    problems.push('no negative-control record at tools/p2/rederivation-controls.json — eight checks that '
      + 'have never been watched to fire are eight claims');
  } else {
    const rec = JSON.parse(readFileSync(CONTROL, 'utf8'));
    const proven = new Set((rec.controls ?? []).filter((c) => c.fired).map((c) => c.id));
    const unproven = interfaces.map((i) => i.id).filter((id) => !proven.has(id));
    if (unproven.length) problems.push('no control that fired for: ' + unproven.join(', '));
    lines.push('');
    lines.push('  controls        ' + proven.size + ' of ' + interfaces.length + ' checks watched to fire · recorded ' + (rec.recordedAt ?? '?'));
  }

  if (problems.length) return fail(problems.length + ' problem(s): ' + problems.slice(0, 4).join(' · '), lines.join('\n'));

  return {
    ...ok(SENTINEL, lines.join('\n')),
    sentinelOverride: 'NO-REDERIVATION OK — ' + cleared + ' of ' + interfaces.length + ' interfaces',
  };
};
