/**
 * GATE: ob7-organisation-kinds — criterion A5, OB-7, Owner Decisions OD-28 / OD-30.
 *   →  `OB-7 OK — 3 kinds, 0 invented labels`
 *
 *   > **A5.** *"The three organisation kinds shipping `labelState: UNKNOWN_NOT_IN_ESTATE` render
 *   > the key or an own UI string and **switch on `labelState`**; **no key is title-cased into an
 *   > estate-looking label**."*
 *
 *   > **OD-30.** *"P1 must **not invent, translate, infer or synthesize** display labels."*
 *
 * Flagged **L13b**.
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * THE COUNT COMES FROM THE SHIPPED PACK
 *
 * `tools/p2/org-kinds.json` is generated by `campaign-p2/bin/p2-org-kinds.mjs` from
 * `dist/packs/taxonomy/pack.json` AND cross-checked against OD-30's own list — a divergence between
 * what ships and what was ruled fails there rather than being quietly followed. This gate reads the
 * result, so the number three is never typed anywhere.
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────────
 * WHY TITLE-CASING IS THE THING BEING HUNTED
 *
 * `CONSUMER_CLUB` → "Consumer Club" is one line, reads perfectly, and is a lie. It looks exactly
 * like a label somebody chose, and a reader — or a screenshot, or a support ticket — has no way to
 * tell a rendered enum from an authoritative name. The estate does not say what these are called;
 * displaying a formatted key claims it does. That is why OD-30 lists four verbs and why
 * **synthesize** is one of them.
 *
 * So the gate looks for the transformation, not for the word: any code that lower-cases, splits on
 * underscores, or capitalises words while handling a kind key.
 */
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ok, fail } from '../lib/report.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));

export const CRITERIA = ['A5'];
export const SENTINEL = 'OB-7 OK — 3 kinds, 0 invented labels';

const MIRROR = join(HERE, '..', 'org-kinds.json');
const COMPONENT = 'src/components/OrganisationKindLabel.tsx';

const walk = (dir, acc = []) => {
  if (!existsSync(dir)) return acc;
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) { if (e !== '__tests__') walk(p, acc); }
    else if (/\.(ts|tsx)$/.test(e)) acc.push(p);
  }
  return acc;
};

const stripComments = (src) => {
  const blank = (t) => t.replace(/[^\n]/g, ' ');
  return src.replace(/\/\*[\s\S]*?\*\//g, blank)
    .replace(/(^|[^:])(\/\/[^\n]*)/g, (m, b, c) => b + blank(c));
};

const lineAt = (code, i) => code.slice(0, i).split('\n').length;

/** The shapes that turn an enum key into something that reads like a name. */
const SYNTHESIS = [
  [/\.toLowerCase\s*\(\)[\s\S]{0,80}?\breplace\s*\(/g, 'lower-cases and rewrites a key'],
  [/\bsplit\s*\(\s*['"`]_['"`]\s*\)/g, 'splits a key on underscores'],
  [/\breplace\s*\(\s*\/_\/[a-z]*\s*,/g, 'replaces underscores in a key'],
  [/\bcharAt\s*\(\s*0\s*\)\s*\.toUpperCase\s*\(\)/g, 'capitalises the first letter of a word'],
  [/\btitleCase\b|\bstartCase\b|\bhumanize\b|\bhumanise\b/g, 'calls a title-casing helper'],
];

export const run = async ({ root }) => {
  const problems = [];
  const lines = [];

  if (!existsSync(MIRROR)) {
    return fail('tools/p2/org-kinds.json is missing. The count comes from the SHIPPED taxonomy pack '
      + 'via campaign-p2/bin/p2-org-kinds.mjs, and this gate will not type the number three itself');
  }
  const mirror = JSON.parse(readFileSync(MIRROR, 'utf8'));
  const kinds = mirror.kinds ?? [];
  if (kinds.length === 0) {
    return fail('the mirror carries no kinds — "0 kinds, 0 invented labels" is not a pass');
  }

  // Every kind must still be label-less. The mirror is generated, but a stale mirror is possible.
  for (const k of kinds) {
    if (k.label !== null) {
      problems.push(k.key + ' carries a label (' + JSON.stringify(k.label) + ') while its labelState '
        + 'is ' + k.labelState + '. OD-30 forbids inventing, translating, inferring or synthesizing one');
    }
    if (k.labelState !== 'UNKNOWN_NOT_IN_ESTATE') {
      problems.push(k.key + ' has labelState ' + k.labelState + ', not UNKNOWN_NOT_IN_ESTATE');
    }
  }

  // ── the component exists and switches on labelState ──────────────────────────────
  if (!existsSync(join(root, COMPONENT))) {
    return fail(COMPONENT + ' does not exist. A5 asks for a renderer that switches on labelState, '
      + 'and a gate that passed without one would be asserting discipline over nothing');
  }
  const componentSrc = stripComments(readFileSync(join(root, COMPONENT), 'utf8'));

  if (!/switch\s*\(\s*[\w.]*labelState\s*\)/.test(componentSrc)) {
    problems.push(COMPONENT + ' does not switch on labelState. A5 says switch on the STATE: '
      + '`label === null` is one symptom of one state, and a future state — a label withheld for '
      + 'licensing, say — would also be null and would need saying differently');
  }
  if (!/UNKNOWN_NOT_IN_ESTATE/.test(componentSrc)) {
    problems.push(COMPONENT + ' never names UNKNOWN_NOT_IN_ESTATE — it cannot be handling it');
  }
  // It must render the key itself somewhere.
  if (!/\{\s*kind\.key\s*\}/.test(componentSrc)) {
    problems.push(COMPONENT + ' does not render kind.key. A5 permits the key OR an own UI string, '
      + 'and this component is where that choice lives');
  }

  // ── nobody synthesises a label from a key ────────────────────────────────────────
  const files = walk(join(root, 'src'));
  if (files.length === 0) return fail('scanned 0 files — an empty population proves nothing');

  const invented = [];
  for (const abs of files) {
    const rel = relative(root, abs).replace(/\\/g, '/');
    const code = stripComments(readFileSync(abs, 'utf8'));
    // Only where a kind key is in play: the whole app lower-cases strings for other reasons.
    const touchesKinds = /labelState|organisationKind|organizationKind|NON_MERCHANT_ORGANISATION_KIND/.test(code)
      || kinds.some((k) => code.includes(k.key));
    if (!touchesKinds) continue;
    for (const [re, what] of SYNTHESIS) {
      for (const m of code.matchAll(re)) {
        invented.push({ file: rel, line: lineAt(code, m.index), what });
      }
    }
  }
  for (const i of invented.slice(0, 5)) {
    problems.push(i.file + ':' + i.line + ' ' + i.what + ' while handling an organisation kind. '
      + 'CONSUMER_CLUB → "Consumer Club" reads perfectly and is a lie: the estate does not say what '
      + 'these are called, and a formatted key claims it does');
  }

  // ── the key must not appear title-cased anywhere as a literal ────────────────────
  const titleCased = kinds.map((k) => ({
    key: k.key,
    text: k.key.toLowerCase().split('_').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' '),
  }));
  for (const abs of files) {
    const rel = relative(root, abs).replace(/\\/g, '/');
    const code = stripComments(readFileSync(abs, 'utf8'));
    for (const t of titleCased) {
      const at = code.indexOf(t.text);
      if (at !== -1) {
        problems.push(rel + ':' + lineAt(code, at) + ' contains "' + t.text + '" — that is ' + t.key
          + ' title-cased into an estate-looking label, which is exactly what A5 forbids');
      }
    }
  }

  lines.push('source          ' + mirror.source + ' · cross-checked against ' + mirror.ruledBy);
  lines.push('kinds           ' + kinds.length);
  for (const k of kinds) lines.push('  ' + k.key.padEnd(26) + 'label ' + JSON.stringify(k.label) + ' · ' + k.labelState);
  lines.push('');
  lines.push('renderer        ' + COMPONENT + ' · switches on labelState · renders the key as a key');
  lines.push('population      ' + files.length + ' files searched for synthesis · found ' + invented.length);

  if (problems.length) return fail(problems.length + ' problem(s): ' + problems.slice(0, 4).join(' · '), lines.join('\n'));

  return {
    ...ok(SENTINEL, lines.join('\n')),
    sentinelOverride: 'OB-7 OK — ' + kinds.length + ' kinds, 0 invented labels',
  };
};
